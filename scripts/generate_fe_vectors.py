"""Generate shared Fe constants and the native runner from validated fixtures."""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

from hashmark.fixtures import Fixture, load_fixtures

DEFAULT_FE_BINARY = "fe"


def _constant_name(fixture_id: str) -> str:
    return fixture_id.upper().replace("-", "_").replace(".", "_")


def _array(name: str, fixtures: list[Fixture], attribute: str) -> list[str]:
    values = [getattr(item, attribute) for item in fixtures]
    cast = " as usize" if attribute == "input_length_bytes" else ""
    formatted = ", ".join(f"{value}{cast}" for value in values)
    value_type = "usize" if attribute == "input_length_bytes" else "u256"
    return [f"pub const {name}: [{value_type}; {len(values)}] = [{formatted}]", ""]


def generate_constants(fixtures: list[Fixture]) -> str:
    lines = ["// Generated by scripts/generate_fe_vectors.py. Do not edit manually.", ""]
    for item in fixtures:
        lines.append(f"pub const {_constant_name(item.id)}: u256 = 0x{item.expected_digest_hex}")
    lines.append("")
    for algorithm in ("sha256", "keccak256"):
        generated = [
            item
            for item in fixtures
            if item.algorithm == algorithm and item.category in {"boundary", "long_message"}
        ]
        prefix = algorithm.upper()
        lines.extend(_array(f"{prefix}_GENERATED_LENGTHS", generated, "input_length_bytes"))
        digests = ", ".join(_constant_name(item.id) for item in generated)
        lines.append(f"pub const {prefix}_GENERATED_DIGESTS: [u256; {len(generated)}] = [{digests}]")
        lines.append("")
    return "\n".join(lines)


def _input_expression(item: Fixture) -> str:
    if item.input_hex == "":
        return "[0 as u8; 0]"
    if item.input_hex == "616263":
        return "[97 as u8, 98, 99]"
    if item.input_hex == "d3":
        return "[0xd3 as u8]"
    return f"deterministic_input({item.input_length_bytes}).span()"


def generate_runner(fixtures: list[Fixture]) -> str:
    lines = [
        "#![cfg(target = \"native\")]",
        "",
        "use core::text::hex",
        "use std::env::Args",
        "use std::io::{Stderr, Stdout}",
        "",
        "use super::digest_check::DigestCheck",
        "use super::{conformance, deterministic_input, generated_vectors, keccak256, sha256}",
        "",
        "fn emit<const I: usize, const A: usize>(",
        "    _ vector_id: String<I>,",
        "    _ algorithm: String<A>,",
        "    _ input_length: usize,",
        "    _ check: DigestCheck,",
        ") -> bool uses (out: mut Stdout) {",
        "    let passed = check.passes()",
        "    println!(",
        "        \"HASHMARK/1\\t\", vector_id, \"\\t\", algorithm, \"\\t\", input_length,",
        "        \"\\t\", hex(check.observed(), 32), \"\\tnative\\t\",",
        "        if passed { \"pass\" } else { \"fail\" },",
        "    )",
        "    passed",
        "}",
        "",
        "pub fn run() -> i32 uses (args: Args, out: mut Stdout, err: mut Stderr) {",
        "    let argument_count = args.count()",
        "    let select_all = argument_count == 1 || (argument_count == 2 && args.get(1) == \"--all\")",
        "    let select_algorithm = argument_count == 3 && args.get(1) == \"--algorithm\"",
        "    let select_vector = argument_count == 3 && args.get(1) == \"--vector\"",
        "    let select_self_test = argument_count == 2 && args.get(1) == \"--self-test\"",
        "    if !(select_all || select_algorithm || select_vector || select_self_test) {",
        "        eprintln!(\"usage: hashmark [--all | --algorithm sha256|keccak256 | --vector id | --self-test]\")",
        "        return 2",
        "    }",
        "    if select_self_test {",
        "        let passed = conformance::streaming_suite()",
        "        println!(\"HASHMARK/SELFTEST/1\\t\", if passed { \"pass\" } else { \"fail\" })",
        "        return if passed { 0 } else { 1 }",
        "    }",
        "    if select_algorithm && !(args.get(2) == \"sha256\" || args.get(2) == \"keccak256\") {",
        "        eprintln!(\"unsupported algorithm\")",
        "        return 2",
        "    }",
        "    var known_vector = false",
    ]
    for item in fixtures:
        lines.append(f"    if select_vector && args.get(2) == \"{item.id}\" {{ known_vector = true }}")
    lines.extend(
        [
            "    if select_vector && !known_vector {",
            "        eprintln!(\"unknown vector id\")",
            "        return 2",
            "    }",
            "    var total: usize = 0",
            "    var passed: usize = 0",
        ],
    )
    for item in fixtures:
        check_call = "sha256::check" if item.algorithm == "sha256" else "keccak256::check"
        constant = _constant_name(item.id)
        lines.extend(
            [
                f"    if select_all || (select_algorithm && args.get(2) == \"{item.algorithm}\")",
                f"        || (select_vector && args.get(2) == \"{item.id}\") {{",
                "        total += 1",
                f"        if emit(\"{item.id}\", \"{item.algorithm}\", {item.input_length_bytes},",
                f"            {check_call}({_input_expression(item)}, generated_vectors::{constant})) {{",
                "            passed += 1",
                "        }",
                "    }",
            ],
        )
    lines.extend(
        [
            "    let failed = total - passed",
            "    println!(\"HASHMARK/1\\tSUMMARY\\t\", total, \"\\t\", passed, \"\\t\", failed)",
            "    if failed == 0 { 0 } else { 1 }",
            "}",
            "",
        ],
    )
    return "\n".join(lines)


def _format_generated_sources(project_root: Path) -> None:
    fe_binary = os.environ.get("HASHMARK_FE_BIN", DEFAULT_FE_BINARY)
    try:
        subprocess.run(
            [fe_binary, "fmt", "src"],
            cwd=project_root,
            check=True,
        )
    except FileNotFoundError as error:
        raise SystemExit(f"Fe formatter not found: {fe_binary}") from error


def main() -> int:
    project_root = Path(__file__).resolve().parents[1]
    fixtures = load_fixtures(project_root / "vectors")
    (project_root / "src/generated_vectors.fe").write_text(
        generate_constants(fixtures), encoding="utf-8", newline="\n",
    )
    (project_root / "src/native_runner.fe").write_text(
        generate_runner(fixtures), encoding="utf-8", newline="\n",
    )
    _format_generated_sources(project_root)
    print(f"generated Fe data for {len(fixtures)} vectors")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
